"""Regenerate docs/tools.md from the live server schemas:  uv run python scripts/gen_tool_docs.py"""

from __future__ import annotations

import asyncio
import tempfile
from pathlib import Path

from sheetmcp import build_server
from sheetmcp_core import Config


def _type(s: dict) -> str:
    if "anyOf" in s:
        return " | ".join(_type(x) for x in s["anyOf"])
    if "enum" in s:
        return " / ".join(f"`{v}`" for v in s["enum"])
    t = s.get("type", "any")
    if t == "array":
        return f"list[{_type(s.get('items', {}))}]"
    if t == "object":
        return "object"
    return str(t)


async def main() -> None:
    with tempfile.TemporaryDirectory() as d:
        server = build_server(Config(roots=[d]))
        tools = await server.list_tools()
        prompts = await server.list_prompts()
        templates = await server.list_resource_templates()
        resources = await server.list_resources()
    out = [
        "# Tool reference",
        "",
        "_Generated by `scripts/gen_tool_docs.py` from the server's live schemas._",
        "",
    ]
    for t in tools:
        out += [f"## `{t.name}`", "", (t.description or "").strip(), ""]
        ann = t.annotations
        if ann:
            out.append(f"_read-only: {ann.readOnlyHint}, destructive: {ann.destructiveHint}_\n")
        props = t.inputSchema.get("properties", {})
        req = set(t.inputSchema.get("required", []))
        if props:
            out += [
                "| Parameter | Type | Required | Default | Description |",
                "| --- | --- | --- | --- | --- |",
            ]
            for name, s in props.items():
                default = "" if name in req else f"`{s.get('default')!r}`"
                desc = (s.get("description") or "").replace("|", "\\|").replace("\n", " ")
                typ = _type(s).replace("|", "\\|")
                flag = "yes" if name in req else ""
                out.append(f"| `{name}` | {typ} | {flag} | {default} | {desc} |")
            out.append("")
    out += ["# Resources", ""]
    out += [f"* `{r.uri}`: {r.description}" for r in resources]
    out += [f"* `{r.uriTemplate}`: {r.description}" for r in templates]
    out += [
        "* `sheet://describe/<file>`: one concrete resource per file found at startup (first 100)",
        "",
        "# Prompts",
        "",
    ]
    for p in prompts:
        args = ", ".join(f"`{a.name}`{'' if a.required else '?'}" for a in (p.arguments or []))
        out.append(f"* **{p.name}**({args}): {p.description}")
    path = Path(__file__).resolve().parent.parent / "docs" / "tools.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    asyncio.run(main())
